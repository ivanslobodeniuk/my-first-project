<?php

// Перевірка, чи форма була надіслана методом POST
if ($_SERVER["REQUEST_METHOD"] == "POST") {
    // Отримання даних з форми
    $name = htmlspecialchars(trim($_POST['name'])); // Очищення і захист від XSS
    $age = intval($_POST['age']); // Приведення віку до числа

    // Перевірка валідності даних
    if (!empty($name) && $age > 0) {
        // Виведення результату
        echo "<h1>Привіт, $name!</h1>";
        echo "<p>Вам $age років.</p>";
    } else {
        // Повідомлення про помилку
        echo "<h1>Помилка!</h1>";
        echo "<p>Будь ласка, введіть коректні дані.</p>";
    }
} else {
    // Якщо сторінка відкрита напряму без форми
    echo "<h1>Доступ заборонений</h1>";
    echo "<p>Будь ласка, поверніться до форми.</p>";
}

